<?php

namespace Larazoul\Larazoul;

use Illuminate\Foundation\Console\AboutCommand;
use Illuminate\Support\ServiceProvider;
use Larazoul\Larazoul\Commands\InstallCommand;
use Larazoul\Larazoul\Commands\MakeModuleCommand;
use Larazoul\Larazoul\Http\Middleware\AdminMiddleware;
use Larazoul\Larazoul\Http\Middleware\SetLocaleMiddleware;
use Larazoul\Larazoul\Livewire\Admin\ModuleWizard;
use Livewire\Livewire;

class LarazoulServiceProvider extends ServiceProvider
{
    /**
     * Register services.
     */
    public function register(): void
    {
        $this->mergeConfigFrom(__DIR__ . '/../config/larazoul.php', 'larazoul');

        $this->registerHelpers('arrays');
        $this->registerHelpers('path');
        $this->registerHelpers('crud');
        $this->registerHelpers('lang');
        $this->registerHelpers('function');
    }

    /**
     * Bootstrap services.
     */
    public function boot(): void
    {
        $this->loadMigrationsFrom(__DIR__ . '/../database/migrations');
        $this->loadTranslationsFrom(__DIR__ . '/../src/Resources/lang', 'larazoul');
        $this->loadViewsFrom(__DIR__ . '/../src/Resources/views', 'larazoul');
        $this->loadRoutesFrom(__DIR__ . '/../routes/web.php');

        $this->loadGeneratedRoutes();

        $this->publishes([
            __DIR__ . '/../config/larazoul.php' => config_path('larazoul.php'),
        ], 'larazoul-config');

        $this->publishes([
            __DIR__ . '/../src/Resources/views' => resource_path('views/vendor/larazoul'),
        ], 'larazoul-views');

        $this->publishes([
            __DIR__ . '/../src/Resources/lang' => lang_path('vendor/larazoul'),
        ], 'larazoul-lang');

        $this->registerMiddleware();
        $this->registerLivewireComponents();
        $this->registerCommands();

        AboutCommand::add('LaraZoul', fn () => [
            'Version' => '4.0.0',
            'Engine' => 'Blade + Tailwind + Livewire',
        ]);
    }

    /**
     * Load routes generated by the module builder (app routes/larazoul*.php).
     *
     * The wrapper keeps Laravel from scanning app route files directly while
     * still exposing the routes the generator produced.
     */
    protected function loadGeneratedRoutes(): void
    {
        $moduleRoutes = base_path('routes/larazoul.php');
        $apiRoutes = base_path('routes/larazoul-api.php');

        if (file_exists($moduleRoutes)) {
            $this->loadRoutesFrom($moduleRoutes);
        }

        if (file_exists($apiRoutes)) {
            $this->loadRoutesFrom($apiRoutes);
        }
    }

    /**
     * Register route middleware aliases.
     */
    protected function registerMiddleware(): void
    {
        $router = $this->app['router'];

        $router->aliasMiddleware('larazoul.admin', AdminMiddleware::class);
        $router->aliasMiddleware('larazoul.locale', SetLocaleMiddleware::class);
        $router->aliasMiddleware('larazoul.setLocale', SetLocaleMiddleware::class);
    }

    /**
     * Register Livewire components exposed by the package.
     */
    protected function registerLivewireComponents(): void
    {
        if (! class_exists(Livewire::class)) {
            return;
        }

        Livewire::component('admin.module-wizard', ModuleWizard::class);
    }

    /**
     * Register console commands.
     */
    protected function registerCommands(): void
    {
        if (! $this->app->runningInConsole()) {
            return;
        }

        $this->commands([
            InstallCommand::class,
            MakeModuleCommand::class,
        ]);
    }

    /**
     * Register a helpers file (loaded once).
     */
    protected function registerHelpers(string $file): void
    {
        $path = __DIR__ . '/Helpers/' . $file . '.php';

        if (file_exists($path)) {
            require_once $path;
        }
    }
}
